
-- =====================================
-- DATABASE LAPORKU
-- =====================================

-- =====================================
-- 1. TABEL KATEGORI
-- =====================================

CREATE TABLE public.kategori (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL UNIQUE,

    CONSTRAINT kategori_nama_valid
    CHECK (char_length(trim(nama)) BETWEEN 3 AND 30)
);

-- =====================================
-- 2. TABEL LAPORAN
-- =====================================

CREATE TABLE public.laporan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode TEXT UNIQUE,
    kategori_id BIGINT NOT NULL
        REFERENCES public.kategori(id),
    judul TEXT NOT NULL,
    deskripsi TEXT NOT NULL,
    lokasi TEXT NOT NULL,
    pelapor TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'baru',
    tanggapan TEXT,
    dukungan INTEGER NOT NULL DEFAULT 0,
    dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT laporan_judul_valid
    CHECK (char_length(trim(judul)) BETWEEN 5 AND 80),

    CONSTRAINT laporan_deskripsi_valid
    CHECK (char_length(trim(deskripsi)) BETWEEN 10 AND 500),

    CONSTRAINT laporan_lokasi_valid
    CHECK (char_length(trim(lokasi)) BETWEEN 3 AND 60),

    CONSTRAINT laporan_pelapor_valid
    CHECK (char_length(trim(pelapor)) BETWEEN 3 AND 40),

    CONSTRAINT laporan_status_valid
    CHECK (status IN ('baru', 'diproses', 'selesai')),

    CONSTRAINT laporan_dukungan_valid
    CHECK (dukungan >= 0)
);

-- =====================================
-- 3. FUNCTION KODE LAPORAN
-- =====================================

CREATE OR REPLACE FUNCTION public.buat_kode_laporan()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.kode := 'LP-' || LPAD(NEW.id::TEXT, 4, '0');
    RETURN NEW;
END;
$$;

CREATE TRIGGER trigger_kode_laporan
BEFORE INSERT ON public.laporan
FOR EACH ROW
EXECUTE FUNCTION public.buat_kode_laporan();

-- =====================================
-- 4. FUNCTION WAKTU DIPERBARUI
-- =====================================

CREATE OR REPLACE FUNCTION public.update_waktu_laporan()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.diperbarui := NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trigger_update_waktu
BEFORE UPDATE ON public.laporan
FOR EACH ROW
EXECUTE FUNCTION public.update_waktu_laporan();

-- =====================================
-- 5. INDEX
-- =====================================

CREATE INDEX idx_laporan_kategori
ON public.laporan(kategori_id);

CREATE INDEX idx_laporan_status
ON public.laporan(status);

CREATE INDEX idx_laporan_dibuat
ON public.laporan(dibuat DESC);

-- =====================================
-- 6. ROW LEVEL SECURITY
-- =====================================

ALTER TABLE public.kategori ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.laporan ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Publik membaca kategori"
ON public.kategori
FOR SELECT
TO anon, authenticated
USING (true);

-- =====================================
-- 7. TABEL DUKUNGAN
-- =====================================

CREATE TABLE public.dukungan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laporan_id BIGINT NOT NULL
        REFERENCES public.laporan(id) ON DELETE CASCADE,
    pengunjung_id TEXT NOT NULL,
    dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT dukungan_satu_kali
    UNIQUE (laporan_id, pengunjung_id)
);

ALTER TABLE public.dukungan ENABLE ROW LEVEL SECURITY;

-- =====================================
-- 8. FUNCTION JUMLAH DUKUNGAN
-- =====================================

CREATE OR REPLACE FUNCTION public.tambah_jumlah_dukungan()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE public.laporan
    SET dukungan = dukungan + 1
    WHERE id = NEW.laporan_id;

    RETURN NEW;
END;
$$;

CREATE TRIGGER setelah_dukungan_ditambahkan
AFTER INSERT ON public.dukungan
FOR EACH ROW
EXECUTE FUNCTION public.tambah_jumlah_dukungan();

-- =====================================
-- 9. HAK AKSES SERVICE ROLE
-- =====================================

GRANT ALL PRIVILEGES
ON TABLE public.laporan TO service_role;

GRANT ALL PRIVILEGES
ON TABLE public.kategori TO service_role;

GRANT ALL PRIVILEGES
ON TABLE public.dukungan TO service_role;

GRANT USAGE, SELECT
ON ALL SEQUENCES IN SCHEMA public
TO service_role;

